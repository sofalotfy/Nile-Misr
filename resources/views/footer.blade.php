        <!-- Booking Modal Script -->
        <script>
        $(document).ready(function() {
            let currentPrices = { single: 0, double: 0, triple: 0, quad: 0 };
            let currentMax = 2; // Default double

            function formatCurrency(num) {
                if(!num) return '0';
                return num.toString().replace(/\B(?=(\d{3})+(?!\d))/g, ",");
            }

            function parsePrice(str) {
                if(!str) return 0;
                return parseInt(str.toString().replace(/,/g, ''));
            }

            function calculateTotal() {
                let selectedRoom = $('input[name="bm-room-type"]:checked').val();
                let pp = currentPrices[selectedRoom] || 0;
                let qty = parseInt($('#bm-travelers-qty').val()) || 1;
                let total = pp * qty;

                $('#bm-summary-pp').text(formatCurrency(pp) + ' جنية');
                $('#bm-summary-total').text(formatCurrency(total));
            }

            $(document).on('click', '.open-booking-modal', function(e) {
                e.preventDefault();
                let btn = $(this);
                
                $('#bm-package-name').text(btn.data('name'));
                $('#bm-program-type').text(btn.data('type') === 'hajj' ? 'الحج' : 'العمرة');
                $('#bm-date').text(btn.data('date'));
                $('#bm-duration').text(btn.data('duration'));
                $('#bm-category').text(btn.data('category'));

                currentPrices = {
                    single: parsePrice(btn.data('price-single')),
                    double: parsePrice(btn.data('price-double')),
                    triple: parsePrice(btn.data('price-triple')),
                    quad: parsePrice(btn.data('price-quad'))
                };

                // Update labels
                $('#bm-price-single').text(formatCurrency(currentPrices.single));
                $('#bm-price-double').text(formatCurrency(currentPrices.double));
                $('#bm-price-triple').text(formatCurrency(currentPrices.triple));
                $('#bm-price-quad').text(formatCurrency(currentPrices.quad));

                // Hide if not available
                if(currentPrices.single === 0 || isNaN(currentPrices.single)) {
                    $('#bm-room-single-wrapper').hide();
                    if($('#bm-room-single').is(':checked')) $('#bm-room-double').prop('checked', true);
                } else {
                    $('#bm-room-single-wrapper').show();
                }

                if(currentPrices.double === 0 || isNaN(currentPrices.double)) $('#bm-room-double-wrapper').hide(); else $('#bm-room-double-wrapper').show();
                if(currentPrices.triple === 0 || isNaN(currentPrices.triple)) $('#bm-room-triple-wrapper').hide(); else $('#bm-room-triple-wrapper').show();
                if(currentPrices.quad === 0 || isNaN(currentPrices.quad)) $('#bm-room-quad-wrapper').hide(); else $('#bm-room-quad-wrapper').show();

                // Trigger change to update max travelers
                $('input[name="bm-room-type"]:checked').trigger('change');
                $('#bm-travelers-qty').val(1);
                calculateTotal();
                
                let modal = new bootstrap.Modal(document.getElementById('bookingModal'));
                modal.show();
            });

            $('input[name="bm-room-type"]').on('change', function() {
                let type = $(this).val();
                if(type === 'single') currentMax = 1;
                else if(type === 'double') currentMax = 2;
                else if(type === 'triple') currentMax = 3;
                else if(type === 'quad') currentMax = 5;

                let qtyEl = $('#bm-travelers-qty');
                let currentQty = parseInt(qtyEl.val());
                if(currentQty > currentMax) {
                    qtyEl.val(currentMax);
                }
                $('#bm-qty-warning').addClass('d-none');
                calculateTotal();
            });

            $('#bm-qty-plus').on('click', function() {
                let qtyEl = $('#bm-travelers-qty');
                let currentQty = parseInt(qtyEl.val());
                if(currentQty < currentMax) {
                    qtyEl.val(currentQty + 1);
                    $('#bm-qty-warning').addClass('d-none');
                } else {
                    // shake warning
                    let warning = $('#bm-qty-warning');
                    warning.removeClass('d-none');
                    warning.addClass('shake-anim');
                    setTimeout(() => warning.removeClass('shake-anim'), 500);
                }
                calculateTotal();
            });

            $('#bm-qty-minus').on('click', function() {
                let qtyEl = $('#bm-travelers-qty');
                let currentQty = parseInt(qtyEl.val());
                if(currentQty > 1) {
                    qtyEl.val(currentQty - 1);
                    $('#bm-qty-warning').addClass('d-none');
                }
                calculateTotal();
            });

            $('#bm-confirm-btn').on('click', function() {
                if($('#premiumBookingForm')[0].checkValidity()) {
                    alert('تم ارسال طلب الحجز بنجاح!');
                    bootstrap.Modal.getInstance(document.getElementById('bookingModal')).hide();
                } else {
                    $('#premiumBookingForm')[0].reportValidity();
                }
            });
        });
        </script>
